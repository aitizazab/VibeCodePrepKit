using System.Collections.Generic;
using JamKit.Patterns;
using UnityEngine;
using SVector2 = System.Numerics.Vector2;

namespace JamKit.BulletHell
{
    /// <summary>
    /// Every bullet on screen: two core <see cref="BulletPool"/>s (enemy and player shots) in struct
    /// arrays, stepped by the game each frame and drawn with GPU instancing. No GameObject per bullet.
    /// Emitters write into <see cref="Spawns"/> (a reused list) and <see cref="EmitEnemy"/> copies them in.
    /// Bullet looks (colour, size, stretch) come from the config's bullet styles.
    /// </summary>
    public sealed class BulletField : MonoBehaviour
    {
        [Tooltip("JamKit/BulletInstanced material (generated by the builder).")]
        public Material material;
        public int enemyCapacity = 4096;
        public int playerCapacity = 768;
        [Tooltip("How far outside the playfield a bullet may go before it's removed.")]
        public float cullMargin = 0.8f;
        [Header("Draw depth (smaller = in front)")]
        public float enemyZ = -1f;
        public float playerZ = 0.5f;

        BulletPool _enemy, _player;
        InstancedQuads _enemyQuads, _playerQuads;
        readonly List<BulletSpawn> _spawns = new List<BulletSpawn>(512);
        readonly List<float> _radii = new List<float>();
        readonly List<BulletStyle> _styles = new List<BulletStyle>();
        PlayfieldBounds _bounds = PlayfieldBounds.Centered(6f, 5.3f);
        float _enemyTimeScale = 1f;

        public BulletPool Enemy { get { Ensure(); return _enemy; } }
        public BulletPool Player { get { Ensure(); return _player; } }
        /// <summary>Scratch list for emitters: clear, Tick an emitter into it, then <see cref="EmitEnemy"/>.</summary>
        public List<BulletSpawn> Spawns => _spawns;
        public PlayfieldBounds Bounds => _bounds;
        public IReadOnlyList<float> StyleRadii => _radii;

        /// <summary>Enemy bullets move at this fraction of game time (1 normally; Time Dilation slows only the
        /// bullets near the ship, with BulletPool.SlowNear).</summary>
        public float EnemyTimeScale
        {
            get => _enemyTimeScale;
            set => _enemyTimeScale = Mathf.Clamp(value, 0f, 2f);
        }

        void Awake() => Ensure();

        void Ensure()
        {
            if (_enemy != null) return;
            _enemy = new BulletPool(Mathf.Max(16, enemyCapacity));
            _player = new BulletPool(Mathf.Max(16, playerCapacity));
            _enemyQuads = new InstancedQuads(material, enemyCapacity);
            _playerQuads = new InstancedQuads(material, playerCapacity);
        }

        public void Configure(List<BulletStyle> styles, PlayfieldBounds bounds)
        {
            Ensure();
            _bounds = bounds;
            _styles.Clear();
            _radii.Clear();
            if (styles != null)
                foreach (var s in styles)
                {
                    _styles.Add(s);
                    _radii.Add(s != null ? s.hitRadius : 0.1f);
                }
        }

        public float RadiusOf(int style) => style >= 0 && style < _radii.Count ? _radii[style] : 0.1f;

        /// <summary>Copies <see cref="Spawns"/> (or another list) into the enemy pool.</summary>
        public int EmitEnemy(List<BulletSpawn> spawns) => Enemy.AddSpawns(spawns, _radii);

        /// <summary>A player shot with explicit flags (homing, bounce, falloff, ricochet), advanced by <paramref name="age"/>.</summary>
        public bool FirePlayer(Vector2 position, float angleRad, float speed, float damage, int style, float lifetime, int pierce, BulletFlags flags, float age)
        {
            var dir = new Vector2(Mathf.Cos(angleRad), Mathf.Sin(angleRad));
            Vector2 p = position + dir * (speed * age);
            return Player.Spawn(new SVector2(p.x, p.y), angleRad, speed, style, RadiusOf(style), lifetime > 0f ? lifetime - age : 0f,
                0f, 0f, damage, pierce, flags);
        }

        /// <summary>A player shot, advanced by <paramref name="age"/> seconds so streams stay evenly spaced.
        /// <paramref name="bounce"/>: it bounces once off the bottom edge, hotter (Rebound).</summary>
        public bool FirePlayer(Vector2 position, float angleRad, float speed, float damage, int style, float lifetime, int pierce, bool homing, float age,
            bool bounce = false)
        {
            var dir = new Vector2(Mathf.Cos(angleRad), Mathf.Sin(angleRad));
            Vector2 p = position + dir * (speed * age);
            var flags = (homing ? BulletFlags.Homing : BulletFlags.None) | (bounce ? BulletFlags.Bounce : BulletFlags.None);
            return Player.Spawn(new SVector2(p.x, p.y), angleRad, speed, style, RadiusOf(style), lifetime > 0f ? lifetime - age : 0f,
                0f, 0f, damage, pierce, flags);
        }

        /// <summary>Moves both pools by dt (enemy bullets by dt x EnemyTimeScale) and culls.</summary>
        public void Tick(float dt)
        {
            Ensure();
            _enemy.Step(dt * _enemyTimeScale, _bounds, cullMargin);
            _player.Step(dt, _bounds, cullMargin);
        }

        public void ClearAll()
        {
            Ensure();
            _enemy.Clear();
            _player.Clear();
        }

        void LateUpdate()
        {
            if (_enemy == null || !InstancedQuads.CanDraw) return;
            Fill(_playerQuads, _player);
            Fill(_enemyQuads, _enemy);
            _playerQuads.Draw(playerZ);
            _enemyQuads.Draw(enemyZ);
        }

        void Fill(InstancedQuads quads, BulletPool pool)
        {
            quads.Clear();
            var items = pool.Items;
            int n = pool.Count;
            float z = 0f;
            for (int i = 0; i < n; i++)
            {
                ref Bullet b = ref items[i];
                var style = b.style >= 0 && b.style < _styles.Count ? _styles[b.style] : null;
                float size = style != null ? style.size : 0.25f;
                float stretch = style != null ? Mathf.Max(1f, style.stretch) : 1f;
                Color c = style != null ? style.color : Color.white;
                // Fade in over the first few frames so bullets don't pop.
                if (b.age < 0.06f) c.a *= Mathf.Clamp01(b.age / 0.06f + 0.3f);
                quads.Add(b.position.X, b.position.Y, z, b.angle, size * stretch, size, c);
            }
        }
    }
}
